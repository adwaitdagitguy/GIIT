"""
graph_service.py
================
Service layer for causal graph representation and custom quantity mutation.

Wraps existing functions from:
  - utils/physics_utils.py : build_node_explanations
  - core/dynamic_intervener.py : DynamicSciMLIntervener (for custom-quantity mutation)

Strictly handles graph metadata extraction, conversion to React Flow format,
and adding custom composite quantities into the intervener's residual spec.
No intervention logic lives here.
"""

from utils.physics_utils import build_node_explanations
from backend.session_manager import session_store


# Default React Flow positions layout helper
# Spaces nodes in columns by type: inputs (left) -> intermediates/params (middle) -> outputs (right)
_TYPE_COLUMNS = {
    "input": 0,
    "parameter": 1,
    "intermediate": 2,
    "state": 2,
    "output": 3,
}

_COL_X_SPACING = 250
_ROW_Y_SPACING = 120


def get_react_flow_graph(session_id: str) -> dict:
    """
    Build a React Flow-compatible representation of the session's physics graph.

    Nodes are positioned heuristically by their causal category (input -> param -> state -> output).
    Includes rich node explanations generated by build_node_explanations().

    Args:
        session_id : UUID of the active ModelSession.

    Returns:
        dict ready for GraphResponse serialization.
    """
    session = session_store.get(session_id)
    graph_data = session.graph_data
    physics_rules = session.physics_ruleset

    # 1. Build node explanations using existing physics_utils.py function
    explanations = build_node_explanations(graph_data, physics_rules)

    # 2. Assign deterministic layout positions
    raw_nodes = graph_data.get("nodes", [])
    col_counters = {0: 0, 1: 0, 2: 0, 3: 0}

    nodes = []
    for node in raw_nodes:
        if isinstance(node, dict):
            node_id = node.get("id", node.get("name", ""))
            node_label = node.get("label", node_id)
            node_type = node.get("type", "state")
            node_symbol = node.get("symbol", "")
        else:
            node_id = str(node)
            node_label = str(node)
            node_type = "state"
            node_symbol = ""

        if not node_id:
            continue

        col = _TYPE_COLUMNS.get(node_type, 2)
        row = col_counters[col]
        col_counters[col] += 1

        pos_x = col * _COL_X_SPACING + 50
        pos_y = row * _ROW_Y_SPACING + 50

        expl = explanations.get(node_id, {})

        nodes.append({
            "id": node_id,
            "type": node_type,
            "data": {
                "label": node_label,
                "symbol": node_symbol,
                "explanation": expl,
            },
            "position": {"x": float(pos_x), "y": float(pos_y)},
        })

    # 3. Format edges
    raw_edges = graph_data.get("edges", [])
    edges = []
    for idx, e in enumerate(raw_edges):
        if isinstance(e, dict):
            src = e.get("source", "")
            tgt = e.get("target", "")
        elif isinstance(e, (list, tuple)) and len(e) >= 2:
            src, tgt = str(e[0]), str(e[1])
        else:
            continue

        edges.append({
            "id": f"e-{src}-{tgt}-{idx}",
            "source": src,
            "target": tgt,
            "animated": False,
        })

    return {
        "session_id": session_id,
        "nodes": nodes,
        "edges": edges,
        "metadata": graph_data.get("metadata", {}),
        "node_explanations": explanations,
    }


def add_custom_quantity(
    session_id: str,
    name: str,
    vars_to_combine: list[str],
    operation: str = "add",
) -> dict:
    """
    Define a custom composite quantity (e.g. u * u_x or x + x_dot) and attach
    it dynamically to the intervener's residual spec and graph nodes.

    Matches existing custom quantity behavior from app.py lines 505-544
    and dynamic_intervener.py lines 108-121.

    Args:
        session_id      : UUID of active ModelSession.
        name            : Name for the composite quantity (e.g. "Q_custom").
        vars_to_combine : List of base variable names to combine.
        operation       : "add" or "multiply".

    Returns:
        dict ready for CustomQuantityResponse serialization.
    """
    session = session_store.get(session_id)
    intervener = session.intervener

    # Ensure derivatives spec exists in residual
    if "derivatives" not in intervener.residual_spec:
        intervener.residual_spec["derivatives"] = {}

    op_key = "multiply" if "mult" in operation.lower() else "add"

    # Register custom derivative computation definition
    intervener.residual_spec["derivatives"][name] = {
        "type": "custom",
        "operation": op_key,
        "vars": vars_to_combine,
    }

    # Add synthetic node to graph.nodes if not already present
    existing_node_ids = {
        n.get("id", n.get("name", "")) if isinstance(n, dict) else str(n)
        for n in intervener.graph.get("nodes", [])
    }
    if name not in existing_node_ids:
        op_symbol = " * " if op_key == "multiply" else " + "
        synthetic_formula = op_symbol.join(vars_to_combine)
        intervener.graph.setdefault("nodes", []).append({
            "id": name,
            "label": f"Custom: {name}",
            "type": "intermediate",
            "symbol": name,
            "formula": synthetic_formula,
            "description": f"Custom composite quantity computed as {synthetic_formula}.",
        })

    return {
        "session_id": session_id,
        "name": name,
        "operation": op_key,
        "vars": vars_to_combine,
        "added_to_graph": True,
    }
